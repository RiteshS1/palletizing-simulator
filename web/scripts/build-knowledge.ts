// Build the assistant's knowledge index (src/generated/knowledge.ts) from:
//   - the docs (en + ja MDX), split by "## " sections
//   - the C++ engine and ROS 2 sources, split into ~60-line chunks
//   - the README and the concept notes
// Run: npm run knowledge (also runs automatically before dev, build and test).
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { buildIndex, type KnowledgeChunk } from "../src/lib/ai/bm25";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(web, "..");
const chunks: KnowledgeChunk[] = [];

function walk(dir: string, exts: string[]): string[] {
  let out: string[] = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (["build", "node_modules", ".git"].includes(e.name)) continue;
      out = out.concat(walk(p, exts));
    } else if (exts.some((x) => e.name.endsWith(x))) out.push(p);
  }
  return out;
}

// A docs page's first real paragraph (not a heading, table, list, code or component), for <meta description>.
function firstParagraph(src: string): string {
  const para = src
    .split(/\n\s*\n/)
    .map((b) => b.trim())
    .find((b) => b && !/^(#|\||[-*] |\d+\. |```|<|export |import )/.test(b));
  if (!para) return "";
  const text = para.replace(/\*\*|`|\[|\]\([^)]*\)/g, "").replace(/\s+/g, " ").trim();
  return text.length > 158 ? `${text.slice(0, 155).replace(/\s+\S*$/, "")}…` : text;
}
const descriptions: Record<string, string> = {};

// ---- docs
for (const locale of ["en", "ja"] as const) {
  const messages = JSON.parse(readFileSync(join(web, "messages", `${locale}.json`), "utf8"));
  const dir = join(web, "src/content/docs", locale);
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".mdx"))) {
    const slug = basename(file, ".mdx");
    descriptions[`${locale}/${slug}`] = firstParagraph(readFileSync(join(dir, file), "utf8"));
    const page = messages.docs.pages[slug] ?? slug;
    const url = `/${locale}/docs${slug === "overview" ? "" : `/${slug}`}`;
    const body = readFileSync(join(dir, file), "utf8")
      .replace(/^export .*$/gm, "")
      .replace(/<\/?[A-Z][A-Za-z]*[^>]*>/g, "");
    const sections = body.split(/^## /m);
    sections.forEach((s, i) => {
      const heading = i === 0 ? "" : s.split("\n")[0].trim();
      const text = (i === 0 ? s.replace(/^# .*$/m, "") : s.slice(s.indexOf("\n") + 1)).trim();
      if (text.length < 40) return;
      chunks.push({ id: `${locale}:${slug}:${i}`, title: heading ? `${page} — ${heading}` : page, url, locale, kind: "doc", text });
    });
  }
}

// ---- C++ engine + ROS 2 package
const codeFiles = [
  ...walk(join(repo, "core/include"), [".hpp"]),
  ...walk(join(repo, "core/src"), [".cpp"]),
  ...walk(join(repo, "core/apps"), [".cpp"]),
  ...walk(join(repo, "core/wasm"), [".cpp"]),
  ...walk(join(repo, "ros2"), [".cpp", ".hpp", ".srv", ".py"]),
  join(repo, "core/CMakeLists.txt"),
  join(repo, "core/vcpkg.json"),
];
for (const f of codeFiles) {
  const rel = relative(repo, f);
  const lines = readFileSync(f, "utf8").split("\n");
  for (let i = 0; i < lines.length; i += 60) {
    const text = lines.slice(i, i + 70).join("\n").trim();
    if (text.length < 40) continue;
    chunks.push({ id: `code:${rel}:${i}`, title: `${rel} (lines ${i + 1}-${Math.min(lines.length, i + 70)})`, kind: "code", text });
  }
}

// ---- notes
for (const [file, title] of [
  ["README.md", "Project README"],
  ["idea/concepts.md", "Concept notes"],
  ["idea/idea.md", "Project idea"],
] as const) {
  const sections = readFileSync(join(repo, file), "utf8").split(/^## /m);
  sections.forEach((s, i) => {
    const heading = s.split("\n")[0].trim();
    if (s.trim().length < 40) return;
    chunks.push({ id: `notes:${file}:${i}`, title: `${title} — ${heading}`.slice(0, 120), kind: "notes", text: s.trim() });
  });
}

const index = buildIndex(chunks);
mkdirSync(join(web, "src/generated"), { recursive: true });
// Emitted as a module that parses a string: TypeScript only sees a string (instead of inferring a
// type for a 1.5 MB object literal), and JSON.parse is faster for V8 than an equivalent literal.
writeFileSync(
  join(web, "src/generated/knowledge.ts"),
  `// Generated by scripts/build-knowledge.ts. Do not edit.\nimport type { KnowledgeIndex } from "@/lib/ai/bm25";\n\nconst knowledge: KnowledgeIndex = JSON.parse(${JSON.stringify(JSON.stringify(index))});\nexport default knowledge;\n`,
);
writeFileSync(
  join(web, "src/generated/doc-descriptions.ts"),
  `// Generated by scripts/build-knowledge.ts. Do not edit.\nexport const DOC_DESCRIPTIONS: Record<string, string> = ${JSON.stringify(descriptions, null, 2)};\n`,
);
console.log(`knowledge: ${chunks.length} chunks, ${Object.keys(index.df).length} terms; ${Object.keys(descriptions).length} page descriptions`);
